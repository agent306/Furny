/**
 * The furniture fixtures of 03 §6 (besides the 07 §12.2 wardrobe, which
 * `wardrobe_hinged.test.ts` checks): each is a template's document, generated
 * with the seed catalog and the deterministic ids of 07 §12.1.
 *
 * `UPDATE_FIXTURES=1` rewrites the files (prettier-formatted, so a rewrite of
 * an unchanged document is byte-identical); otherwise they are compared.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { beforeAll, describe, expect, it } from 'vitest';
import { testIds } from '../../../testing/ids';
import { seedCatalog } from '../../../testing/seedCatalog';
import { indexCatalog } from '../../catalogIndex';
import {
    FurnitureDocumentSchema,
    type FurnitureDocument,
    type Section,
    type TemplateKey,
} from '../../schema';
import { validateFurniture } from '../../validate';
import { getTemplate } from '../index';

const FIXTURE_DIR = '../../../../../../database/fixtures/furniture/';
const fixtureUrl = (file: string): URL =>
    new URL(`${FIXTURE_DIR}${file}`, import.meta.url);
const UPDATE = process.env['UPDATE_FIXTURES'] === '1';

const snapshot = seedCatalog();

/** The document of `key` for its defaults overridden by `over`. */
function generate(
    key: TemplateKey,
    over: Record<string, unknown>,
): FurnitureDocument {
    const template = getTemplate(key);
    return template.generate(
        { ...template.defaults, ...over },
        { catalog: indexCatalog(seedCatalog()), newId: testIds() },
    );
}

/** The fixture file text: the document as prettier formats it (2-space JSON). */
async function fixtureText(file: string, doc: FurnitureDocument) {
    const prettier = await import('prettier');
    const path = fileURLToPath(fixtureUrl(file));
    const config = (await prettier.resolveConfig(path)) ?? {};
    // JSON needs no plugin; the project's tailwind plugin only formats classes.
    return prettier.format(JSON.stringify(doc), {
        ...config,
        plugins: [],
        filepath: path,
    });
}

const FIXTURES: Array<[string, TemplateKey, Record<string, unknown>]> = [
    ['tv-unit-1800.json', 'tv_unit', {}],
    // ih = 2004 at height 2100: shelfCount(2004, 330) = 5 shelves per column
    ['bookshelf-5shelf.json', 'bookshelf', { height: 2100 }],
    ['kitchen-base-600.json', 'base_cabinet', {}],
    ['dining-table-6seat.json', 'dining_table', {}],
    ['study-desk-cabinet.json', 'study_desk', {}],
];

describe.each(FIXTURES)('%s', (file, key, over) => {
    const doc = generate(key, over);

    beforeAll(async () => {
        if (UPDATE)
            writeFileSync(fixtureUrl(file), await fixtureText(file, doc));
    });

    it(`is the ${key} document generated by the template`, () => {
        const golden: unknown = JSON.parse(
            readFileSync(fixtureUrl(file), 'utf8'),
        );
        expect(golden).toStrictEqual(doc);
    });

    it('is written exactly as the formatter writes it (byte-identical rewrite)', async () => {
        expect(readFileSync(fixtureUrl(file), 'utf8')).toBe(
            await fixtureText(file, doc),
        );
    });

    it('parses as a FurnitureDocument and generates deterministically', () => {
        expect(() => FurnitureDocumentSchema.parse(doc)).not.toThrow();
        expect(generate(key, over)).toStrictEqual(doc);
    });

    it('validates with no error and no warning', () => {
        expect(
            validateFurniture(doc, snapshot)
                .filter((i) => i.severity !== 'info')
                .map((i) => i.code),
        ).toStrictEqual([]);
    });
});

describe('bookshelf-5shelf.json', () => {
    const leaves = (s: Section): Section[] =>
        s.split === 'none' ? [s] : s.children.flatMap((c) => leaves(c.section));

    it('has 5 shelves in every column at height 2100', () => {
        const doc = generate('bookshelf', { height: 2100 });
        const counts = leaves(doc.carcass?.interior as Section).map((leaf) =>
            leaf.content?.type === 'shelves' ? leaf.content.count : null,
        );
        expect(counts).toStrictEqual([5, 5]);
    });
});
