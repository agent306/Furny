describe('engine public API', () => {
    it('exports every public name', () => {
        const exported = new Set(Object.keys(engine));
        expect(PUBLIC_NAMES.filter((name) => !exported.has(name))).toEqual([]);
    });

    it('exports nothing that is not listed', () => {
        const listed = new Set<string>(PUBLIC_NAMES);
        expect(Object.keys(engine).filter((name) => !listed.has(name))).toEqual(
            [],
        );
    });

    it('lists no name twice', () => {
        expect(new Set(PUBLIC_NAMES).size).toBe(PUBLIC_NAMES.length);
    });

    it('exports nothing from a testing/ directory', () => {
        const modules = import.meta.glob<Record<string, unknown>>(
            '../**/testing/*.ts',
            { eager: true },
        );
        expect(Object.keys(modules).length).toBeGreaterThan(5);
        const leaked: string[] = [];
        for (const [path, mod] of Object.entries(modules)) {
            for (const [name, value] of Object.entries(mod)) {
                if (
                    name in engine &&
                    (engine as Record<string, unknown>)[name] === value
                ) {
                    leaked.push(`${path}: ${name}`);
                }
            }
        }
        expect(leaked).toEqual([]);
        for (const name of [
            'testIds',
            'mulberry32',
            'seedCatalog',
            'mutateCatalog',
            'buildHdb3Room',
            'buildBrochure2Bhk',
            'testDrawingOptions',
            'measure',
            'perfWardrobe',
            'randomParts',
        ]) {
            expect(Object.keys(engine)).not.toContain(name);
        }
    });
});
